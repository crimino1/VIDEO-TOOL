from common import *


def P(*xy):
    return np.array([xy[0], xy[1], 0.0])


def out_pos(p, q, mob, buff=0.28):
    """Centre for a label outside edge p->q of a counter-clockwise triangle (outside = right of p->q)."""
    d = q - p
    n = np.array([d[1], -d[0], 0]) / np.linalg.norm(d)
    return (p + q) / 2 + n * (buff + abs(n[0]) * mob.width / 2 + abs(n[1]) * mob.height / 2)


def slab(p, q, tex, color, size=46, buff=0.25):
    m = M(tex, size=size, color=color)
    return m.move_to(out_pos(p, q, m, buff))


def vlab(V, tex, color, size=46, away=0.45, others=()):
    """Vertex letter just outside the corner V (pushed away from the triangle's centroid)."""
    c = sum(others) / len(others) if others else ORIGIN
    d = V - c
    d = d / np.linalg.norm(d)
    return M(tex, size=size, color=color).move_to(V + d * away)


def rows(*ms, top=1.6, x=2.9, gap=0.42):
    g = VGroup(*ms).arrange(DOWN, aligned_edge=LEFT, buff=gap)
    g.move_to([x, 0, 0]).align_to([0, top, 0], UP)
    return g


